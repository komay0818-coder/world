const assert=require('node:assert/strict');
const {member,run,isolate,activeMatrix}=require('./offline-skill-fixture');
const count=activeMatrix('assassin');
const m=isolate('assassin','backstab');
m.nextAttackAt=1000000;
const r=run([m],4900,{trace:true,random:()=>.5});
assert.equal(r.members[0].combatTelemetry.dotTicks,2,'bleed only ticks at two and four seconds');
assert.equal(r.members[0].resourceCurrent,74,'natural recovery caps before the second backstab, then recovers nine energy');
const p=isolate('assassin','poison-blade',{tier:6});p.nextAttackAt=1000000;
const poison=run([p],6000,{trace:true,random:()=>.5});
assert.equal(poison.members[0].combatTelemetry.dotTicks,3);
const dual=member('assassin',{tier:6,equipment:{offhand:{series:'匕首',attack:30,weaponType:'one-handed-dagger'}}});
assert.ok(run([dual],3000,{random:()=>0}).members[0].combatTelemetry.offhandAttacks>0);
const mixed=run([member('assassin',{advancedClass:'venom',tier:6})],30000,{trace:true,random:()=>0});
assert.ok(mixed.members[0].combatTelemetry.dotTicks>0);
assert.ok(mixed.members[0].combatTelemetry.maxDotStacks.bleed<=7,'blood-venom group caps at six; ordinary backstab bleed remains a separate group');
assert.ok(mixed.members[0].combatTelemetry.dotEvents.filter(e=>e.type==='bleed' && e.added!==undefined).every(e=>e.stacks<=6));
assert.ok(mixed.members[0].combatTelemetry.maxDotStacks.poison<=6);
console.log(`offline assassin: ${count} active level cases and DOT/offhand checks passed`);
