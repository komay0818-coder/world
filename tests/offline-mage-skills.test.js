const assert=require('node:assert/strict');
const {member,run,isolate,activeMatrix}=require('./offline-skill-fixture');
const count=activeMatrix('mage');
const f=isolate('mage','fireball');f.nextAttackAt=1000000;
const burn=run([f],600,{trace:true,random:()=>.5});
assert.equal(burn.members[0].combatTelemetry.dotTicks,4,'legacy burning follows actual 100ms online DOT cadence');
const empty=member('mage',{resource:0});empty.nextAttackAt=1000000;
const regen=run([empty],1000,{random:()=>.5});
assert.ok(regen.members[0].manaExhausted);assert.equal(regen.members[0].resourceCurrent,10);
assert.deepEqual(regen.members[0].combatTelemetry.skillCasts,{});
const arc=isolate('mage','arcane-missile',{advancedClass:'arcane-mage',tier:6});arc.nextAttackAt=1000000;
const missiles=run([arc],100,{random:()=>.5});
assert.equal(missiles.members[0].mageTelemetry.arcaneMissilesFired,4);
assert.equal(missiles.members[0].mageTelemetry.arcaneMissilesHit,4);
const converted=isolate('mage','fireball',{advancedClass:'arcane-mage',tier:6});
assert.equal(run([converted],1000).members[0].combatTelemetry.dotTicks,0,'conversion suppresses base burn');
const elements=run([member('mage',{advancedClass:'elementalist',tier:6})],30000,{random:()=>0});
assert.ok(elements.members[0].mageTelemetry.resonanceTriggers>0);
const expiring=isolate('mage','fireball',{advancedClass:'elementalist',tier:6});
expiring.skillCooldowns.fireball=100000000;expiring.nextAttackAt=1000000;
expiring.resonanceUntil=2000;expiring.lastElement='fire';
const released=run([expiring],1100);
assert.equal(released.members[0].mageTelemetry.overloadReleases,1,'expiry releases despite every active skill being unavailable');
assert.equal(released.members[0].mageTelemetry.overloadHits,1,'single target release settles once');
console.log(`offline mage: ${count} active level cases and mana/element checks passed`);
