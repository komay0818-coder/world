const assert=require('node:assert/strict');
const {member,run,isolate,activeMatrix}=require('./offline-skill-fixture');
const count=activeMatrix('priest');
const healer=isolate('priest','heal',{tier:6,hp:1000,currentHp:100});healer.nextAttackAt=1000000;
const before=run([healer],2900,{random:()=>.5});
const after=run([healer],3100,{random:()=>.5});
assert.equal(before.members[0].currentHp,353,'actual Lv6 holy faith adds 15% healing once');
assert.equal(after.members[0].currentHp,404,'one delayed heal after three seconds');
assert.equal(after.members[0].priestTelemetry.effectiveHealingBySource.afterglow,51);
const sanctuary=isolate('priest','guardian-sanctuary',{advancedClass:'holy-priest',hp:1000,currentHp:100});
sanctuary.nextAttackAt=1000000;
assert.equal(run([sanctuary],6100,{random:()=>.5}).members[0].priestTelemetry.sanctuaryHealing,45);
const nova=isolate('priest','holy-nova',{tier:6});
assert.equal(run([nova],100).members[0].shield,0,'single enemy cannot trigger three-target shield');
const main=member('warrior',{hp:1000,currentHp:300}), priest=isolate('priest','heal',{id:'p',isMain:false,tier:1});
main.nextAttackAt=1000000;priest.nextAttackAt=1000000;
const party=run([main,priest],100,{random:()=>.5});
assert.equal(party.members[0].currentHp,456,'lowest HP ratio receives healing including actual Lv1 holy faith');
const pending=isolate('priest','heal',{hp:1000,currentHp:100});
pending.skillCooldowns.heal=100000000;pending.nextAttackAt=1000000;
pending.classHealSequence=1;
pending.pendingClassHeals=[{id:1,dueAt:4000,targetId:'main',amount:50}];
assert.equal(run([pending],2900).members[0].currentHp,100);
assert.equal(run([pending],3100).members[0].currentHp,150,'departure snapshot retains pending class healing');
assert.equal(run([pending],6000).members[0].currentHp,150,'restored healing cannot settle twice');
console.log(`offline priest: ${count} active level cases and healing/shield checks passed`);
